const CRISIS_RE = /(үхмээр|амиа\s*хорло|өөрийгөө\s*(гэмтээ|ал)|амьдрах\s*хүсэл\s*(алга|байхгүй)|амьдрахыг\s*хүсэхгүй|алга\s*болмоор|бүх\s*юм\s*дуусаасай)/;
export const isCrisisText = (t: string) => CRISIS_RE.test(t.toLowerCase());
