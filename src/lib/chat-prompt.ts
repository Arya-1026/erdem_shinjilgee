const fmt = (e: Entry) => `${e.entry_date}: ${moodById(e.mood).label} (эрч хүч ${e.intensity}/5${e.sleep != null ? `, нойр ${e.sleep}ц` : ''}${e.tags.length ? `, ${e.tags.join('/')}` : ''})`;

