import { describe, expect, it } from 'vitest';
import { speechFilter } from './speech';

// Хөтчөөс ирэх эцсийн үр дүнгүүдийг дарааллаар нь өгч, талбарт орох текстийг буцаана
const run = (events: [number, string][]) => {
  const next = speechFilter();
  return events.map(([i, t]) => next(i, t)).filter(Boolean).join(' ');
};

describe('дуугаар бичих давхардал', () => {
  it('хэвийн хөтөч: үр дүн бүр нэг удаа', () => {
    expect(run([[0, 'сайн байна уу'], [1, ' өнөөдөр сайхан өдөр']])).toBe('сайн байна уу өнөөдөр сайхан өдөр');
  });
  it('Android: өмнөх үр дүн дахин ирэхэд давтахгүй', () => {
    expect(run([[0, 'сайн байна'], [0, 'сайн байна'], [1, 'уу'], [0, 'сайн байна'], [1, 'уу']])).toBe('сайн байна уу');
  });
  it('Android: үр дүн өмнөхөө агуулж ирэхэд зөвхөн шинэ үг нэмнэ', () => {
    expect(run([[0, 'сайн'], [1, 'сайн байна'], [2, 'сайн байна уу']])).toBe('сайн байна уу');
    expect(run([[0, 'сайн'], [0, 'сайн байна'], [0, 'Сайн байна уу.']])).toBe('сайн байна уу.');
  });
  it('нэг өгүүлбэр доторх санаатай давталтыг хадгална', () => {
    expect(run([[0, 'тийм тийм зөв']])).toBe('тийм тийм зөв');
  });
  it('шинэ сонсолт өмнөхөөс хамаарахгүй', () => {
    expect(run([[0, 'сайн']])).toBe('сайн');
    expect(run([[0, 'сайн']])).toBe('сайн');
  });
});
